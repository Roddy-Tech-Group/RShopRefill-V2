<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Renders the Records of Processing Activities (NDPA 2023 / GAID 2025) from
 * config/retention.php. Retention figures are substituted from the same keys
 * the enforcement commands read, so the register can never quote a window the
 * system does not actually run. Re-run after any change to the register or
 * the windows and commit the result.
 */
class RetentionRopaCommand extends Command
{
    protected $signature = 'retention:ropa
        {--write : Write to docs/compliance/records-of-processing.md instead of printing}';

    protected $description = 'Render the Records of Processing Activities from config/retention.php.';

    public function handle(): int
    {
        $markdown = $this->render();

        if (! $this->option('write')) {
            $this->line($markdown);

            return self::SUCCESS;
        }

        $path = base_path('docs/compliance/records-of-processing.md');
        File::ensureDirectoryExists(dirname($path));
        File::put($path, $markdown);

        $this->info("Written to {$path}");

        return self::SUCCESS;
    }

    public function render(): string
    {
        $controller = config('retention.controller', []);
        $processors = config('retention.processors', []);
        $activities = config('retention.processing_activities', []);

        $lines = [
            '# Records of Processing Activities',
            '',
            'Generated by `php artisan retention:ropa --write` on '.now()->toDateString().'. Do not edit by hand; change `config/retention.php` and re-run.',
            '',
            '## Controller',
            '',
            '| | |',
            '|---|---|',
            '| Controller | '.($controller['name'] ?? '').' |',
            '| Website | '.($controller['website'] ?? '').' |',
            '| Data Protection Officer | '.($controller['dpo_email'] ?? '').' |',
            '| Supervisory authority | Nigeria Data Protection Commission (NDPC) |',
            '',
            '## Retention windows in force',
            '',
            '| Window | Value | Enforced by |',
            '|---|---|---|',
            '| Account closure grace period | '.config('retention.account_closure_grace_days').' days | `retention:close-accounts` (daily) |',
            '| Wallet dust forfeited on closure | under USD '.number_format((float) config('retention.account_closure_dust_threshold_usd'), 2).' | account closure |',
            '| Identity of a closed account that moved money | '.config('retention.closed_account_identity_years').' years after closure | `retention:enforce` (daily) |',
            '| Financial records of a closed account | '.config('retention.closed_account_financial_years').' years after closure | `retention:enforce` (daily) |',
            '| Email delivery logs | '.config('retention.communication_logs_days').' days | `retention:enforce` (daily) |',
            '| Contact-form messages | '.config('retention.contact_messages_days').' days | `retention:enforce` (daily) |',
            '| Fraud and risk assessments | '.config('risk.retention_months', 24).' months | `risk:prune` (daily) |',
            '| Audit logs | '.config('audit.retention_days', 730).' days | `audit:prune` (monthly) |',
            '',
            '## Processing activities',
            '',
        ];

        foreach ($activities as $index => $activity) {
            $lines[] = '### '.($index + 1).'. '.$activity['activity'];
            $lines[] = '';
            $lines[] = '| | |';
            $lines[] = '|---|---|';

            foreach (['purpose' => 'Purpose', 'data' => 'Personal data', 'subjects' => 'Data subjects', 'lawful_basis' => 'Lawful basis', 'recipients' => 'Recipients', 'retention' => 'Retention'] as $key => $label) {
                $lines[] = '| '.$label.' | '.$this->substitute((string) ($activity[$key] ?? '')).' |';
            }

            $lines[] = '';
        }

        $lines[] = '## Processors';
        $lines[] = '';
        $lines[] = '| Processor | Service |';
        $lines[] = '|---|---|';

        foreach ($processors as $name => $service) {
            $lines[] = '| '.$name.' | '.$service.' |';
        }

        $lines[] = '';
        $lines[] = '## Security measures';
        $lines[] = '';
        $lines[] = '- Passwords and transaction PINs stored as one-way hashes; two-factor secrets and the closed-account identity register encrypted at rest.';
        $lines[] = '- Access to customer records restricted to authenticated admin roles; every administrative change to sensitive fields is written to the audit log with the actor.';
        $lines[] = '- Financial tables reject deletion of a customer row at the database level; accounts are closed by anonymisation, never deleted.';
        $lines[] = '- Data export requires a one-time code to the account email; downloads are rate limited and audited.';
        $lines[] = '- Transport encryption (HTTPS) on every endpoint; daily encrypted database backups with retention managed by `backup:clean`.';
        $lines[] = '';
        $lines[] = '## Data subject rights';
        $lines[] = '';
        $lines[] = '- Access: self-serve PDF export from account settings, or by email to the DPO (see `docs/runbooks/data-protection.md`).';
        $lines[] = '- Correction: account settings, or by email to the DPO.';
        $lines[] = '- Deletion: self-serve account closure with a '.config('retention.account_closure_grace_days').'-day grace period, or by email to the DPO (actioned from the admin panel, audited). Records required by financial and anti-money-laundering law are retained for the windows above and then removed.';
        $lines[] = '- Objection and withdrawal of consent: communication preferences in account settings; every marketing email carries an unsubscribe link.';
        $lines[] = '';

        return implode("\n", $lines);
    }

    private function substitute(string $text): string
    {
        return (string) preg_replace_callback('/:([a-z_]+)/', function (array $m): string {
            $value = config('retention.'.$m[1]);

            return $value === null ? $m[0] : (string) $value;
        }, $text);
    }
}
